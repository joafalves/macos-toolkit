#!/usr/bin/env python3
"""The settings search's index (Sources/Toolkit/App/SettingsIndex.swift).

Every settings row (SettingRow, ToggleRow, OptionRow, ShortcutRow, FolderRow, TweakRow)
and card whose title is written out is listed there with its page, so search
finds it and goes to it. Names written by hand in the index (`name:`) are kept.

  python3 scripts/settings-index.py check      # rows missing from the index, or listed but gone
  python3 scripts/settings-index.py generate   # writes the index afresh from the pages
"""
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
INDEX = ROOT / "Sources/Toolkit/App/SettingsIndex.swift"

# Each page's file, and the section it is.
PAGES = {
    "Sources/Toolkit/App/MainView.swift": "general",
    "Sources/Toolkit/App/PermissionsView.swift": "permissions",
    "Sources/Toolkit/App/AboutView.swift": "about",
    "Sources/Toolkit/Mouse/MouseSettingsView.swift": "mouse",
    "Sources/Toolkit/Switcher/SwitcherSettingsView.swift": "switcher",
    "Sources/Toolkit/Layout/LayoutSettingsView.swift": "layout",
    "Sources/Toolkit/Mixer/MixerSettingsView.swift": "mixer",
    "Sources/Toolkit/Finder/FinderSettingsView.swift": "finder",
    "Sources/Toolkit/Capture/CaptureSettingsView.swift": "capture",
    "Sources/Toolkit/Awake/AwakeSettingsView.swift": "awake",
    "Sources/Toolkit/Stats/StatsSettingsView.swift": "stats",
    "Sources/Toolkit/System/TweaksView.swift": "tweaks",
}
# On the Mouse page, the rows of a mouse's own page are in these views.
PER_MOUSE = ("struct ProfileEditor", "struct AutoscrollExceptions")
# Window Layout's tabs, by the view each is built in, and LayoutPage's names.
TABS = {"var snapping": "snapping", "var keyboard": "keyboard", "var tabsPage": "tabs"}

ROW = re.compile(r'\b(?:SettingRow|ToggleRow|OptionRow|ShortcutRow|FolderRow|TweakRow|Card)\(\s*title:\s*"((?:[^"\\]|\\.)*)"')
# A row's caption, or a card's footnote, when it's written out.
CAPTION = re.compile(r'\s*,\s*(?:caption|footnote):\s*"((?:[^"\\]|\\.)*)"\s*[,)]')


def rows():
    """(section, title, caption or None, per mouse) for every row written out."""
    found = []
    for path, section in PAGES.items():
        # Commented-out rows aren't on the page; blanked, so offsets still hold.
        text = re.sub(r"^\s*//.*$", lambda m: " " * len(m.group(0)), (ROOT / path).read_text(), flags=re.M)
        # Where each view of the file starts, to tell a mouse's page apart.
        starts = sorted((m.start(), m.group(0)) for m in re.finditer(r"struct \w+", text))
        tab_starts = sorted((m.start(), m.group(0)) for m in re.finditer(r"var \w+: some View|var body: some View", text))
        for match in ROW.finditer(text):
            title = match.group(1)
            if "\\(" in title:
                continue
            caption = CAPTION.match(text, match.end())
            caption = caption.group(1) if caption and "\\(" not in caption.group(1) else None
            owner = max((s for s in starts if s[0] < match.start()), default=(0, ""))[1]
            per_mouse = section == "mouse" and owner.startswith(PER_MOUSE)
            view = max((s for s in tab_starts if s[0] < match.start()), default=(0, ""))[1]
            tab = TABS.get(view.split(":")[0]) if section == "layout" else None
            entry = (section, title, caption, per_mouse, tab)
            if not any(e[0] == section and e[1] == title for e in found):
                found.append(entry)
    return found


def names():
    """The names written by hand in the index, kept when it's written afresh."""
    text = INDEX.read_text() if INDEX.exists() else ""
    pattern = r'SettingsEntry\(\.(\w+), "((?:[^"\\]|\\.)*)", name: "((?:[^"\\]|\\.)*)"'
    return {(m.group(1), m.group(2)): m.group(3) for m in re.finditer(pattern, text)}


def swift(entries):
    kept = names()
    lines = [
        "import Foundation",
        "",
        "/// Every setting a search finds, with its page: generated by",
        "/// `scripts/settings-index.py generate` from the pages' rows, and checked",
        "/// against them by `scripts/settings-index.py check`. A row goes to it by",
        "/// its title, which is also its anchor on the page. A `name` is written",
        "/// by hand, for a title that only makes sense on its page; generating",
        "/// keeps it.",
        "extension SettingsIndex {",
        "    static let entries: [SettingsEntry] = [",
    ]
    for section, title, caption, per_mouse, tab in entries:
        args = [f".{section}", f'"{title}"']
        if (section, title) in kept:
            args.append(f'name: "{kept[(section, title)]}"')
        if caption:
            args.append(f'caption: "{caption}"')
        if per_mouse:
            args.append("perMouse: true")
        if tab:
            args.append(f'tab: "{tab}"')
        lines.append(f"        SettingsEntry({', '.join(args)}),")
    lines += ["    ]", "}", ""]
    return "\n".join(lines)


def listed():
    text = INDEX.read_text() if INDEX.exists() else ""
    return set(re.findall(r'SettingsEntry\(\.(\w+), "((?:[^"\\]|\\.)*)"', text))


def main():
    command = sys.argv[1] if len(sys.argv) > 1 else "check"
    entries = rows()
    if command == "generate":
        INDEX.write_text(swift(entries))
        print(f"wrote {len(entries)} settings to {INDEX.relative_to(ROOT)}")
        return
    pages = {(e[0], e[1]) for e in entries}
    index = listed()
    missing = sorted(pages - index)
    gone = sorted(index - pages)
    for section, title in missing:
        print(f"  missing  {section}: {title!r}")
    for section, title in gone:
        print(f"  gone     {section}: {title!r}")
    print(f"settings index: {len(index)} listed, {len(missing)} missing, {len(gone)} gone")
    sys.exit(1 if missing or gone else 0)


if __name__ == "__main__":
    main()
